"""
Phase 1: Raw Discovery & Multi-Directory Aggregator
Scrapes and aggregates base business profiles from free, accessible sources:
1. Existing Google Maps leads (ingested from B2B Playwright crawler)
2. Live directory discovery via free public search indexes (YellowPages, Yelp, Manta)
3. Direct directory parsing with automatic anti-block fallbacks
"""

import csv
import re
import random
import urllib.parse
from pathlib import Path
from typing import List, Dict, Any, Optional
import requests
from bs4 import BeautifulSoup

from config import USER_AGENTS, REQUEST_TIMEOUT, RAW_DIR
from utils.helpers import clean_text, normalize_phone, parse_address_components, random_delay, save_json

_DDGS_AVAILABLE = False
try:
    from ddgs import DDGS
    _DDGS_AVAILABLE = True
except ImportError:
    try:
        from duckduckgo_search import DDGS
        _DDGS_AVAILABLE = True
    except ImportError:
        _DDGS_AVAILABLE = False


from .maps_crawler import GoogleMapsCrawler

class RawDiscoveryEngine:
    """Discovers and structures base business leads from Google Maps and free directories."""

    def __init__(self):
        self.session = requests.Session()
        self.maps_crawler = GoogleMapsCrawler(headless=True)

    def _get_headers(self) -> Dict[str, str]:
        return {
            "User-Agent": random.choice(USER_AGENTS),
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.9",
            "DNT": "1",
            "Connection": "keep-alive"
        }

    # ---------------------------------------------------------------------------
    # 1. Ingest existing Google Maps leads from B2B project (Mass Scale)
    # ---------------------------------------------------------------------------
    def ingest_b2b_csv(self, csv_path: Path, limit: Optional[int] = None) -> List[Dict[str, Any]]:
        """Ingests raw verified leads generated by the existing B2B Playwright crawler."""
        leads = []
        if not csv_path.exists():
            print(f"[RAW DISCOVERY] CSV file not found: {csv_path}")
            return leads

        # Treat limit <= 0 as UNLIMITED / MASS MODE
        max_leads = None if (limit is None or limit <= 0) else limit

        with open(csv_path, mode="r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                name = clean_text(row.get("Business Name"))
                phone = normalize_phone(row.get("Phone"))
                address = clean_text(row.get("Address"))
                
                # STRICT AUTHENTICITY FILTER: Must have genuine business name and phone
                if not name or not phone:
                    continue
                    
                parsed_addr = parse_address_components(address)

                lead = {
                    "business_name": name,
                    "category": clean_text(row.get("Category", "Business")),
                    "phone_raw": phone,
                    "email_raw": clean_text(row.get("Email", "")),
                    "full_address": address,
                    "city": clean_text(row.get("City")) or parsed_addr.get("city", ""),
                    "state": clean_text(row.get("State")) or parsed_addr.get("state", ""),
                    "zip": parsed_addr.get("zip", ""),
                    "rating": clean_text(row.get("Rating", "")),
                    "reviews": clean_text(row.get("Reviews", "0")),
                    "source": "google_maps_b2b",
                    "source_url": clean_text(row.get("Google Maps URL", "")),
                    "has_website": False,  # B2B filtered leads are strictly no-website
                }
                leads.append(lead)
                if max_leads and len(leads) >= max_leads:
                    break

        print(f"[RAW DISCOVERY] Ingested {len(leads)} authentic leads from Google Maps ({csv_path.name})")
        return leads

    # ---------------------------------------------------------------------------
    # 2. Free Directory & Index Discovery (YellowPages, Yelp, Manta)
    # ---------------------------------------------------------------------------
    def discover_live_directory_leads(self, category: str, location: str, max_results: int = 15) -> List[Dict[str, Any]]:
        """
        Discovers local businesses from free directory indexes without Cloudflare friction.
        Parses Business Name, Phone Number, Street Address, and City/State.
        """
        leads = []
        print(f"[RAW DISCOVERY] Searching free directory indexes for '{category}' in '{location}'...")

        if not _DDGS_AVAILABLE:
            return leads

        queries = [
            f"{category} in {location} address phone",
            f"{category} in {location} directory hours",
            f"top {category} in {location} reviews phone"
        ]

        seen_names = set()

        try:
            with DDGS() as ddgs:
                for q in queries:
                    if len(leads) >= max_results:
                        break

                    results = list(ddgs.text(q, max_results=max_results))
                    for r in results:
                        title = r.get("title", "")
                        body = r.get("body", "")
                        href = r.get("href", "")

                        # Extract Phone - Genuine business listing MUST have a phone number
                        phone_match = re.search(r'\(?\b[2-9]\d{2}\)?[-.\s]?\d{3}[-.\s]?\d{4}\b', body + " " + title)
                        phone = normalize_phone(phone_match.group(0)) if phone_match else ""
                        if not phone:
                            continue

                        # Extract Business Name
                        clean_title = re.sub(r'(\s*-\s*Yelp|\s*-\s*Yellow Pages|\s*-\s*Manta|\s*\|\s*.*)', '', title).strip()

                        # Discard blog articles, ranking lists, and directory portal pages
                        junk_words = [
                            "directory", "top 10", "best 10", "best beauty", "best hair",
                            "rankings", "blog", "guide", "cities", "near me", "view barbers",
                            "explore", "ratings", "reviews", "salons near", "styleseat"
                        ]
                        if any(jw in clean_title.lower() for jw in junk_words):
                            continue

                        name = ""
                        m_in = re.split(r'\s+in\s+', clean_title, flags=re.I)
                        if len(m_in) > 1 and not m_in[0].lower().startswith(("best", "top", "the best")):
                            name = clean_text(m_in[0])
                        elif not any(w in clean_title.lower() for w in junk_words):
                            name = clean_text(clean_title)

                        if not name or len(name) < 3 or name.lower() in seen_names or any(jw in name.lower() for jw in junk_words):
                            continue

                        # Extract Address components from snippet
                        parsed = parse_address_components(body)
                        city = parsed.get("city") or location.split(",")[0].strip()
                        state = parsed.get("state") or (location.split(",")[1].strip() if "," in location else "")

                        seen_names.add(name.lower())
                        leads.append({
                            "business_name": name,
                            "category": category.title(),
                            "phone_raw": phone,
                            "email_raw": "",
                            "full_address": body[:120].strip(),
                            "city": city,
                            "state": state,
                            "zip": parsed.get("zip", ""),
                            "rating": "",
                            "reviews": "0",
                            "source": "public_directory_index",
                            "source_url": href,
                            "has_website": False
                        })

                        if len(leads) >= max_results:
                            break
        except Exception as e:
            print(f"[RAW DISCOVERY] Directory search notice: {e}")

        print(f"[RAW DISCOVERY] Harvested {len(leads)} live leads from free directory indexes.")
        return leads

    # ---------------------------------------------------------------------------
    # 3. Aggregate & Deduplicate
    # ---------------------------------------------------------------------------
    def aggregate(self, category: str, location: str, b2b_csv: Optional[Path] = None, max_results: int = 25, no_website_only: bool = False) -> List[Dict[str, Any]]:
        """Runs multi-source discovery: first checks existing B2B CSV, then crawls Google Maps via Playwright."""
        all_leads = []

        # 1. Ingest B2B leads if provided
        if b2b_csv and b2b_csv.exists():
            all_leads.extend(self.ingest_b2b_csv(b2b_csv, limit=max_results))

        # 2. If more leads needed, crawl Google Maps directly via Playwright
        if max_results <= 0 or len(all_leads) < max_results:
            needed = max_results - len(all_leads) if max_results > 0 else 0
            maps_leads = self.maps_crawler.crawl_google_maps(category, location, quota=needed, no_website_only=no_website_only)
            all_leads.extend(maps_leads)

        # 3. If Google Maps didn't yield enough, supplement with directory indexes
        if max_results > 0 and len(all_leads) < max_results:
            dir_leads = self.discover_live_directory_leads(category, location, max_results=max_results - len(all_leads))
            all_leads.extend(dir_leads)

        # Deduplication
        deduped = []
        seen_phones = set()
        seen_names = set()

        for lead in all_leads:
            p = lead.get("phone_raw")
            n = (lead.get("business_name") or "").lower().strip()
            city = (lead.get("city") or "").lower().strip()
            key = f"{n}|{city}"

            if p and p in seen_phones:
                continue
            if key in seen_names:
                continue

            if p:
                seen_phones.add(p)
            seen_names.add(key)
            deduped.append(lead)

        return deduped
